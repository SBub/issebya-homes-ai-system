-- Adds whatsapp_messages.langsmith_run_id: the LangSmith trace/run id this
-- message's turn was generated under, if any. Backs the new "flag after"
-- eval-feedback feature (POST /api/messages/[messageId]/feedback in both
-- apps/guest-communication-agent and apps/crm) — the owner can mark a past
-- assistant reply good/bad from the CRM dashboard, recorded as LangSmith
-- feedback attached to that exact turn's trace. Purely retrospective:
-- nothing gates/delays a reply, this column only exists so feedback can be
-- attached after the fact.
--
-- Nullable, deliberately: only a subset of rows ever get a real value.
--   - An assistant reply generated by POST /api/webhook/whatsapp's
--     graph.invoke() call gets one — that route now fixes the trace's run id
--     up front (via crypto.randomUUID(), passed as `runId` in the
--     RunnableConfig) and records it alongside the reply text.
--   - A guest's own inbound message (role = 'user') never has one — nothing
--     is generated on the guest's turn, there is no trace to attach.
--   - A proactive/campaign send recorded by POST /api/send never has one
--     either — that path renders a message template directly and never
--     touches graph.invoke(), so no LangSmith trace exists for it at all.
-- Callers that have no run id simply omit the column from their insert
-- (see apps/guest-communication-agent/src/lib/conversations.ts's
-- recordMessage) rather than writing an explicit null.
alter table public.whatsapp_messages add column langsmith_run_id text;
